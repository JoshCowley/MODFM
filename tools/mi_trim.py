"""FM1 Rack: a Mutable Instruments resources.cc cut to the tables the given objects use.

    tools/mi_trim.py RESOURCES.cc NAMESPACE OUT.cc SYMBOL...

The resources files hold every table a module's firmware has (its UI strings, calibration, other modes); the
FM-1's flash has room for only the ones the DSP calls. The linker here keeps every table of an object (no
--gc-sections in Felucca's link), so the file is cut instead: each top-level `const T name[] = {...};` kept
when NAME is listed (or is referenced by a kept pointer table), the rest left out. SYMBOL...: the names the
DSP objects leave undefined in NAMESPACE (tools/build.py reads them with nm). Unknown names fail.
~NAME: a table the code refers to but never reads in this build (Braids' wavetables, with their models off):
kept as one zero element, and a pointer table's entry for it becomes 0."""
import re
import sys


def main():
    src, ns, out, *want = sys.argv[1:]
    text = open(src).read()
    head = text[:text.index("namespace " + ns)]
    defs = {}
    order = []
    for m in re.finditer(r"^const\s+[\w:]+\s*\*?\s*(\w+)\[\]\s*=\s*\{.*?^\};\n", text, re.M | re.S):
        defs[m.group(1)] = m.group(0)
        order.append(m.group(1))
    stub = {w[1:] for w in want if w.startswith("~")}
    need = {w for w in want if not w.startswith("~")} | stub
    missing = need - set(defs)
    if missing:
        raise SystemExit(f"mi_trim: {src}: not found: {' '.join(sorted(missing))}")
    grew = True
    while grew:                       # pointer tables: the tables they point at
        grew = False
        for n in list(need):
            if n in stub:
                continue
            for ref in re.findall(r"\b(\w+)\b", defs[n].split("{", 1)[1]):
                if ref in defs and ref not in need:
                    need.add(ref)
                    grew = True
    def emit(n):
        d = defs[n]
        if n in stub:                 # one zero element: the symbol links, the table is gone
            return re.sub(r"\[\]\s*=\s*\{.*\};", "[1] = {0};", d, flags=re.S)
        if "*" in d.split("[", 1)[0]:  # a pointer table: entries for stubs are 0
            for s_ in stub:
                d = re.sub(r"\b" + s_ + r"\b", "0", d)
        return d
    body = "".join(emit(n) for n in order if n in need)
    kept = sum(1 for n in order if n in need)
    with open(out, "w") as f:
        f.write("// generated by tools/mi_trim.py from " + src.replace("\\", "/") + ": do not edit\n")
        f.write(head + "namespace " + ns + " {\n\n" + body + "\n}  // namespace " + ns + "\n")
    print(f"mi_trim: {ns}: {kept} of {len(order)} tables -> {out}")


if __name__ == "__main__":
    main()
